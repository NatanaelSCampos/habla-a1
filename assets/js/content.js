// Banco de estruturas: espanhol latino-americano amplo (tú / ustedes, sem voseo).
const STRUCTURES = [];
const GROUPS = [];
function group(name, level, entries) {
  GROUPS.push(name);
  entries.forEach((e, n) => {
    const [title, formula, purpose, tip, pairs, optionalLevel] = e;
    const examples = pairs.split(';;').map((piece, i) => {
      const [es, pt] = piece.split('::').map((s) => s.trim());
      if (!es || !pt) throw new Error('Par inválido: ' + title + ' ' + i);
      return { es, pt, id: `g${GROUPS.length - 1}p${n}e${i}` };
    });
    STRUCTURES.push({
      id: `g${GROUPS.length - 1}p${n}`,
      category: name,
      level: optionalLevel || level,
      title,
      formula,
      purpose,
      tip,
      examples,
    });
  });
}

